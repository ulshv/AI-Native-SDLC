#!/usr/bin/env bash
# The only imperative entry point of the platform. See platform/README.md.
#   platform/bootstrap.sh            build the platform, or converge it; safe to re-run
#   platform/bootstrap.sh --dry-run  print the plan and change nothing
#   platform/bootstrap.sh --example  print secrets.env.example from secrets.manifest
set -euo pipefail
cd "$(dirname "${BASH_SOURCE[0]}")/.."

# Pinned k3s release. Chart versions are pinned in platform/apps/*/app.yaml.
K3S_VERSION=v1.36.5+k3s1

SECRETS_DIR=${SECRETS_DIR:-$HOME/.config/ai-native-sdlc}
SECRETS_FILE=$SECRETS_DIR/secrets.env
CA_KEY=$SECRETS_DIR/ca.key
CA_CRT=$SECRETS_DIR/ca.crt
MANIFEST=platform/secrets.manifest
TOOLS=(helm git openssl jq yq curl certutil)
PORTS=(80 443)

# The script always talks to this cluster, whatever KUBECONFIG the shell had.
export KUBECONFIG=$HOME/.kube/config
FIELD_MANAGER=ai-native-sdlc
HOSTS_BEGIN="# BEGIN ai-native-sdlc"
HOSTS_END="# END ai-native-sdlc"
TRUST_NAME=ai-native-sdlc
SYSTEM_CA=/usr/local/share/ca-certificates/$TRUST_NAME.crt
NSSDB=sql:$HOME/.pki/nssdb
FIREFOX_POLICIES=/etc/firefox/policies/policies.json
FIREFOX_CA=/etc/firefox/policies/$TRUST_NAME-ca.crt
# k3s's default --cluster-cidr: every pod IP is in it.
POD_CIDR=10.42.0.0/16
POD_ROUTE_PRIORITY=100
K3S_ROUTING_DROPIN=/etc/systemd/system/k3s.service.d/ai-native-sdlc-routing.conf
GITEA_HOST=https://gitea.sdlc.internal
GITEA_REPO=sdlc/ai-native-sdlc
GITEA_REMOTE=$GITEA_HOST/$GITEA_REPO.git
# Argo CD reads the repository over the in-cluster Service, not through the ingress.
ARGOCD_REPO_URL=http://gitea-http.gitea.svc:3000/$GITEA_REPO.git
# Created through the Gitea API for this cluster and replaced after a rebuild, so it is not a
# value in secrets.env.
PUSH_TOKEN_FILE=$SECRETS_DIR/gitea-push-token

DRY_RUN=false

log() { printf '%s\n' "$*"; }

# step <description> <check> <action>: runs <action> unless <check> reports it is already done.
# Every change to the host or the cluster goes through a step, which is what makes re-runs
# safe and --dry-run honest.
step() {
  local desc=$1 check=$2 action=$3
  if $check; then
    log "  done  $desc"
  elif $DRY_RUN; then
    log "  todo  $desc"
  else
    log "  run   $desc"
    $action
  fi
}

# secret_value <name>: the value of <name> in secrets.env, empty when absent.
secret_value() {
  [[ -f $SECRETS_FILE ]] || return 0
  sed -n "s/^$1=//p" "$SECRETS_FILE" | tail -n 1
}

required_external_secrets() {
  awk '$1 == "value" && $3 == "external" && $4 == "yes" { print $2 }' "$MANIFEST"
}

# The example secrets.env for humans, derived from the manifest's value lines.
print_example() {
  printf '%s\n' \
    "# Generated from platform/secrets.manifest by: platform/bootstrap.sh --example" \
    "# The real file is ~/.config/ai-native-sdlc/secrets.env (mode 0600). Format: NAME=value," \
    "# no quotes. Never put values into this example."
  awk '$1 == "value" {
    desc = $5; for (i = 6; i <= NF; i++) desc = desc " " $i
    if ($3 == "external") note = ($4 == "yes" ? "external, required" : "external, optional")
    else note = "generated by the bootstrap when empty"
    printf "\n# %s (%s)\n%s=\n", desc, note, $2
  }' "$MANIFEST"
}

# port_holder <port>: names of the processes listening on <port>, empty when it is free.
port_holder() {
  local out
  out=$(sudo -n ss -Hltnp "sport = :$1" 2>/dev/null || ss -Hltnp "sport = :$1")
  [[ -n $out ]] || return 0
  grep -o '"[^"]*"' <<<"$out" | tr -d '"' | sort -u | paste -sd, - | grep . || echo "an unknown process"
}

sudo_available() {
  if $DRY_RUN; then
    # A dry run must not prompt for a password, so it settles for group membership.
    sudo -n true 2>/dev/null || id -nG | grep -qwE 'sudo|admin|wheel'
  else
    sudo -v
  fi
}

# Checks every prerequisite and changes nothing. Reports all problems at once.
phase_preflight() {
  local problems=() tool port holder name
  [[ $EUID -ne 0 ]] || problems+=("running as root: run as your own user, the script calls sudo itself")
  for tool in "${TOOLS[@]}"; do
    command -v "$tool" >/dev/null || problems+=("missing tool: $tool")
  done
  if command -v yq >/dev/null && ! yq --version 2>&1 | grep -q mikefarah; then
    problems+=("wrong yq: need mikefarah/yq v4, not the apt package")
  fi
  sudo_available || problems+=("sudo is not available for $USER")
  for port in "${PORTS[@]}"; do
    holder=$(port_holder "$port")
    [[ -z $holder ]] || problems+=("port $port is in use by $holder")
  done
  for name in $(required_external_secrets); do
    [[ -n $(secret_value "$name") ]] || problems+=("missing secret: $name (add it to $SECRETS_FILE)")
  done

  if [[ ${#problems[@]} -eq 0 ]]; then
    log "  ok    all prerequisites present"
    return 0
  fi
  printf '  FAIL  %s\n' "${problems[@]}" >&2
  $DRY_RUN || exit 1
  PREFLIGHT_FAILED=true
}

secrets_file_private() {
  [[ -f $SECRETS_FILE && $(stat -c %a "$SECRETS_DIR") == 700 && $(stat -c %a "$SECRETS_FILE") == 600 ]]
}

make_secrets_file_private() {
  mkdir -p "$SECRETS_DIR"
  chmod 700 "$SECRETS_DIR"
  touch "$SECRETS_FILE"
  chmod 600 "$SECRETS_FILE"
}

# Generated values that are missing from secrets.env, as "<name> <kind>" lines.
missing_generated_secrets() {
  local name kind
  awk '$1 == "value" && ($3 == "password" || $3 == "key") { print $2, $3 }' "$MANIFEST" |
    while read -r name kind; do
      [[ -n $(secret_value "$name") ]] || echo "$name $kind"
    done
}

generated_secrets_present() { [[ -z $(missing_generated_secrets) ]]; }

# random_secret <length>: random characters from the base58 alphabet (no 0, O, I or l), about
# 5.86 bits each. Letters and digits only, so a value is safe inside URLs and connection
# strings and needs no quoting. Dropping every byte outside the alphabet keeps the remaining
# characters uniform.
random_secret() {
  local chars
  chars=$(openssl rand 1024 | LC_ALL=C tr -dc '1-9A-HJ-NP-Za-km-z')
  ((${#chars} >= $1)) || { echo "error: not enough random characters" >&2; return 1; }
  printf '%s' "${chars:0:$1}"
}

# A password is only hashed or compared, so 128 bits are plenty. A key becomes an encryption or
# signing key inside the app, so it gets 256 bits.
generate_missing_secrets() {
  local name kind value
  # A file edited by hand may lack the final newline; appending would glue two lines.
  [[ ! -s $SECRETS_FILE || -z $(tail -c 1 "$SECRETS_FILE") ]] || echo >>"$SECRETS_FILE"
  missing_generated_secrets | while read -r name kind; do
    case $kind in
      password) value=$(random_secret 22) ;;
      key) value=$(random_secret 44) ;;
    esac
    printf '%s=%s\n' "$name" "$value" >>"$SECRETS_FILE"
    log "        generated $name"
  done
}

ca_valid() {
  [[ -f $CA_KEY && -f $CA_CRT ]] && openssl x509 -checkend $((30 * 86400)) -noout -in "$CA_CRT" >/dev/null
}

# The root CA is valid for one year and may only sign names under sdlc.internal, so a leaked
# key cannot be used to impersonate any other site to this host's browsers. A CA with fewer
# than 30 days left is replaced; phase 2 then swaps the trust over to the new one.
generate_ca() {
  if [[ -f $CA_CRT ]]; then
    mv "$CA_CRT" "$SECRETS_DIR/ca.old.crt"
    [[ ! -f $CA_KEY ]] || mv "$CA_KEY" "$SECRETS_DIR/ca.old.key"
    log "        replaced the expiring CA, kept it as ca.old.{crt,key}"
  fi
  (
    umask 077
    openssl req -x509 -new -noenc -newkey rsa:4096 -days 365 \
      -keyout "$CA_KEY" -out "$CA_CRT" \
      -subj "/CN=ai-native-sdlc local CA" \
      -addext "basicConstraints=critical,CA:TRUE" \
      -addext "keyUsage=critical,keyCertSign,cRLSign" \
      -addext "nameConstraints=critical,permitted;DNS:sdlc.internal" 2>/dev/null
  )
}

# Generates missing secret values and the root CA into the secrets directory.
phase_secrets() {
  step "secrets directory is private (0700/0600)" secrets_file_private make_secrets_file_private
  step "every generated secret has a value" generated_secrets_present generate_missing_secrets
  step "root CA exists and is valid for 30+ days" ca_valid generate_ca
}

k3s_installed() {
  [[ $(k3s --version 2>/dev/null) == *"$K3S_VERSION"* ]] && systemctl is-active -q k3s
}

# The install script comes from the pinned release tag, not from the moving get.k3s.io.
# Bundled Traefik is disabled because Argo CD installs its own; ServiceLB and local-path stay.
install_k3s() {
  local script
  script=$(mktemp)
  curl -sfL "https://raw.githubusercontent.com/k3s-io/k3s/$K3S_VERSION/install.sh" -o "$script"
  sudo env INSTALL_K3S_VERSION="$K3S_VERSION" sh "$script" --disable traefik
  rm -f "$script"
}

kubeconfig_works() {
  [[ $(kubectl config view --minify -o jsonpath='{.clusters[0].cluster.server}' 2>/dev/null) == https://127.0.0.1:6443 ]] &&
    kubectl get --raw /readyz >/dev/null 2>&1
}

# A kubeconfig that was there before is kept once as ~/.kube/config.before-ai-native-sdlc.
write_kubeconfig() {
  mkdir -p "$HOME/.kube"
  if [[ -s $KUBECONFIG && ! -e $KUBECONFIG.before-ai-native-sdlc ]]; then
    cp -p "$KUBECONFIG" "$KUBECONFIG.before-ai-native-sdlc"
  fi
  (umask 077 && sudo cat /etc/rancher/k3s/k3s.yaml >"$KUBECONFIG")
}

# VPN clients in TUN mode (sing-box, Clash, WireGuard, Tailscale) add policy routing rules that
# can steer pod traffic into their tunnel: sing-box sends all port 53 traffic there, so pods'
# DNS queries never reach CoreDNS. A rule ahead of theirs keeps traffic to pods on the main
# table. Traffic from pods to the internet still goes through the VPN.
routing_dropin() {
  local rule="to $POD_CIDR lookup main priority $POD_ROUTE_PRIORITY"
  printf '%s\n' \
    "# Managed by ai-native-sdlc platform/bootstrap.sh: traffic to pods bypasses VPN routing rules." \
    "[Service]" \
    "ExecStartPre=-/bin/sh -c '/usr/sbin/ip rule del $rule 2>/dev/null; /usr/sbin/ip rule add $rule'"
}

pod_routing_in_place() {
  cmp -s <(routing_dropin) "$K3S_ROUTING_DROPIN" &&
    ip rule show pref "$POD_ROUTE_PRIORITY" | grep -qE "^$POD_ROUTE_PRIORITY:\s+from all to $POD_CIDR lookup main"
}

# The drop-in re-adds the rule whenever k3s starts, including after a reboot.
set_pod_routing() {
  local rule="to $POD_CIDR lookup main priority $POD_ROUTE_PRIORITY"
  sudo mkdir -p "$(dirname "$K3S_ROUTING_DROPIN")"
  routing_dropin | sudo tee "$K3S_ROUTING_DROPIN" >/dev/null
  sudo systemctl daemon-reload
  sudo ip rule del $rule 2>/dev/null || true
  sudo ip rule add $rule
}

node_ready() { kubectl get nodes --no-headers 2>/dev/null | grep -qw Ready; }

wait_node_ready() {
  local i
  for i in $(seq 60); do
    node_ready && return 0
    sleep 2
  done
  echo "error: the node is not Ready after 2 minutes" >&2
  return 1
}

# The managed block of /etc/hosts: every name in platform/hosts.txt under sdlc.internal.
hosts_block() {
  local name
  echo "$HOSTS_BEGIN"
  grep -vE '^[[:space:]]*(#|$)' platform/hosts.txt | while read -r name; do
    echo "127.0.0.1 $name.sdlc.internal"
  done
  echo "$HOSTS_END"
}

# hosts_without_block <file>: the file without the managed block.
hosts_without_block() {
  awk -v b="$HOSTS_BEGIN" -v e="$HOSTS_END" '$0 == b { skip = 1 } !skip { print } $0 == e { skip = 0 }' "$1"
}

hosts_current() {
  [[ $(awk -v b="$HOSTS_BEGIN" -v e="$HOSTS_END" '$0 == b { on = 1 } on { print } $0 == e { on = 0 }' /etc/hosts) == "$(hosts_block)" ]]
}

# The first change keeps the original as /etc/hosts.before-ai-native-sdlc.
write_hosts() {
  local tmp
  tmp=$(mktemp)
  { hosts_without_block /etc/hosts; hosts_block; } >"$tmp"
  [[ -e /etc/hosts.before-ai-native-sdlc ]] || sudo cp -p /etc/hosts /etc/hosts.before-ai-native-sdlc
  sudo cp "$tmp" /etc/hosts
  rm -f "$tmp"
}

fingerprint() { openssl x509 -noout -fingerprint -sha256 2>/dev/null; }

system_trusts_ca() { cmp -s "$CA_CRT" "$SYSTEM_CA" && [[ -e /etc/ssl/certs/$TRUST_NAME.pem ]]; }

# Same file name for every CA, so a rotated CA replaces the old one; --fresh drops stale links.
trust_ca_system() {
  sudo install -m 644 "$CA_CRT" "$SYSTEM_CA"
  sudo update-ca-certificates --fresh >/dev/null
}

# Chrome on Linux reads ~/.pki/nssdb.
nss_trusts_ca() {
  [[ -f $CA_CRT && $(certutil -d "$NSSDB" -L -n "$TRUST_NAME" -a 2>/dev/null | fingerprint) == "$(fingerprint <"$CA_CRT")" ]]
}

trust_ca_nss() {
  if [[ ! -f $HOME/.pki/nssdb/cert9.db ]]; then
    mkdir -p "$HOME/.pki/nssdb"
    certutil -d "$NSSDB" -N --empty-password
  fi
  certutil -d "$NSSDB" -D -n "$TRUST_NAME" 2>/dev/null || true
  certutil -d "$NSSDB" -A -t "C,," -n "$TRUST_NAME" -i "$CA_CRT"
}

# Firefox on Linux ignores the system store. Its policy installs the CA from a file under
# /etc/firefox, which the Firefox snap can read.
firefox_trusts_ca() {
  cmp -s "$CA_CRT" "$FIREFOX_CA" &&
    jq -e --arg ca "$FIREFOX_CA" '.policies.Certificates.Install | index($ca)' "$FIREFOX_POLICIES" >/dev/null 2>&1
}

# Merges into an existing policies.json instead of replacing it.
trust_ca_firefox() {
  local tmp
  tmp=$(mktemp)
  { cat "$FIREFOX_POLICIES" 2>/dev/null || echo '{}'; } |
    jq --arg ca "$FIREFOX_CA" '.policies.Certificates.Install = ((.policies.Certificates.Install // []) - [$ca] + [$ca])' >"$tmp"
  sudo mkdir -p "$(dirname "$FIREFOX_POLICIES")"
  sudo install -m 644 "$CA_CRT" "$FIREFOX_CA"
  sudo install -m 644 "$tmp" "$FIREFOX_POLICIES"
  rm -f "$tmp"
}

# expand <template>: the template with every ${NAME} replaced by its value from secrets.env.
expand() {
  local out=$1 name value
  while [[ $out =~ \$\{([A-Za-z0-9_]+)\} ]]; do
    name=${BASH_REMATCH[1]}
    value=$(secret_value "$name")
    [[ -n $value ]] || { echo "error: $name is used in secrets.manifest but has no value" >&2; return 1; }
    out=${out//"\${$name}"/"$value"}
  done
  printf '%s' "$out"
}

# Every Secret from the manifest's put lines, plus the root CA for cert-manager, as one
# kubectl List. Values travel through pipes only, never through command-line arguments.
render_secrets() {
  local target key template value
  {
    awk '$1 == "put" { print $2, $3, $4 }' "$MANIFEST" | while read -r target key template; do
      value=$(expand "$template") || return 1
      printf '%s %s %s\n' "$target" "$key" "$(printf '%s' "$value" | base64 -w0)"
    done
    printf 'cert-manager/root-ca tls.crt %s\n' "$(base64 -w0 <"$CA_CRT")"
    printf 'cert-manager/root-ca tls.key %s\n' "$(base64 -w0 <"$CA_KEY")"
  } | jq -Rn --arg manager "$FIELD_MANAGER" '
    [inputs | split(" ") | {target: .[0], key: .[1], value: .[2]}]
    | group_by(.target)
    | {apiVersion: "v1", kind: "List", items: map({
        apiVersion: "v1",
        kind: "Secret",
        metadata: {
          namespace: (.[0].target | split("/")[0]),
          name: (.[0].target | split("/")[1]),
          labels: {
            "app.kubernetes.io/managed-by": $manager,
            "cnpg.io/reload": "true"
          }
        },
        type: (if any(.key == "tls.crt") then "kubernetes.io/tls" else "Opaque" end),
        data: (map({(.key): .value}) | add)
      })}'
}

ensure_namespace() {
  kubectl create namespace "$1" --dry-run=client -o yaml |
    kubectl apply --server-side --field-manager="$FIELD_MANAGER" -f - >/dev/null
}

secret_namespaces() {
  { awk '$1 == "put" { split($2, t, "/"); print t[1] }' "$MANIFEST"; echo cert-manager; } | sort -u
}

cluster_secrets_current() {
  { render_secrets | kubectl diff --server-side --field-manager="$FIELD_MANAGER" -f -; } >/dev/null 2>&1
}

# Server-side apply keeps no last-applied annotation, so values are not copied into metadata.
# The cnpg.io/reload label makes CloudNativePG pick up a rotated role password.
apply_cluster_secrets() {
  local ns
  for ns in $(secret_namespaces); do
    ensure_namespace "$ns"
  done
  render_secrets | kubectl apply --server-side --field-manager="$FIELD_MANAGER" -f -
}

# cert-manager does not re-issue a certificate when its CA changes, so after a CA rotation the
# wildcard certificate would still chain to the old, no longer trusted CA. Not issued yet
# counts as current: cert-manager will sign it with the CA it has.
wildcard_signed_by_current_ca() {
  local crt
  crt=$(kubectl get secret -n traefik wildcard-sdlc-internal-tls -o jsonpath='{.data.tls\.crt}' 2>/dev/null | base64 -d)
  [[ -z $crt ]] || openssl verify -CAfile "$CA_CRT" <(printf '%s\n' "$crt") >/dev/null 2>&1
}

# Deleting the Secret makes cert-manager issue a new certificate from the current CA.
reissue_wildcard() { kubectl delete secret -n traefik wildcard-sdlc-internal-tls; }

# Installs k3s, the /etc/hosts block and host CA trust, and applies Kubernetes Secrets.
phase_host() {
  step "k3s $K3S_VERSION installed and running" k3s_installed install_k3s
  step "traffic to pods bypasses VPN routing rules" pod_routing_in_place set_pod_routing
  step "~/.kube/config points at k3s" kubeconfig_works write_kubeconfig
  step "node is Ready" node_ready wait_node_ready
  step "/etc/hosts block matches platform/hosts.txt" hosts_current write_hosts
  step "system trust store has the root CA" system_trusts_ca trust_ca_system
  step "Chrome (~/.pki/nssdb) trusts the root CA" nss_trusts_ca trust_ca_nss
  step "Firefox policy installs the root CA" firefox_trusts_ca trust_ca_firefox
  step "Kubernetes Secrets match secrets.env and the root CA" cluster_secrets_current apply_cluster_secrets
  step "the wildcard certificate is signed by the current root CA" wildcard_signed_by_current_ca reissue_wildcard
}

# The bootstrap installs a component from the same app.yaml and values.yaml that Argo CD uses
# later, with the same release name and namespace, so Argo CD adopts it without changes.
# yq reads from stdin: the snap's confinement may not reach every path.

# app_chart <component>: "<repo> <chart> <version> <release>" from its app.yaml.
app_chart() {
  yq -r '.spec.sources[] | select(.chart) | [.repoURL, .chart, .targetRevision, .helm.releaseName] | join(" ")' \
    <"platform/apps/$1/app.yaml"
}

app_namespace() { yq -r '.spec.destination.namespace' <"platform/apps/$1/app.yaml"; }

# Values as compact JSON with sorted keys, so formatting, comments and key order do not count
# as a difference.
normalized_values() { yq -o json -I0 '(. // {}) | sort_keys(..)'; }

helm_release_current() {
  local repo chart version release ns
  read -r repo chart version release <<<"$(app_chart "$1")"
  ns=$(app_namespace "$1")
  [[ $(helm list -n "$ns" -f "^$release\$" -o json 2>/dev/null | jq -r '.[0] | "\(.chart) \(.status)"') == "$chart-$version deployed" ]] &&
    [[ $(helm get values "$release" -n "$ns" -o yaml 2>/dev/null | normalized_values) == \
      "$(normalized_values <"platform/apps/$1/values.yaml")" ]]
}

helm_install() {
  local repo chart version release
  read -r repo chart version release <<<"$(app_chart "$1")"
  helm upgrade --install "$release" "$chart" --repo "$repo" --version "$version" \
    --namespace "$(app_namespace "$1")" --create-namespace \
    --values "platform/apps/$1/values.yaml" --wait --timeout 5m >/dev/null
}

# app_manifests <component>: kubectl -f arguments for its manifests (everything but app.yaml
# and values.yaml).
app_manifests() {
  local file
  for file in "platform/apps/$1"/*.yaml; do
    case ${file##*/} in app.yaml | values.yaml) ;; *) printf -- '-f\n%s\n' "$file" ;; esac
  done
}

manifests_current() {
  local args
  mapfile -t args < <(app_manifests "$1")
  kubectl diff --server-side --field-manager="$FIELD_MANAGER" "${args[@]}" >/dev/null 2>&1
}

apply_manifests() {
  local args
  mapfile -t args < <(app_manifests "$1")
  ensure_namespace "$(app_namespace "$1")"
  kubectl apply --server-side --field-manager="$FIELD_MANAGER" "${args[@]}"
}

platform_pg_healthy() {
  [[ $(kubectl get cluster platform-pg -n databases -o jsonpath='{.status.phase}' 2>/dev/null) == "Cluster in healthy state" ]] &&
    kubectl get database -n databases -o json 2>/dev/null |
    jq -e '(.items | length) > 0 and all(.items[]; .status.applied == true)' >/dev/null
}

wait_platform_pg() {
  local i
  for i in $(seq 100); do
    platform_pg_healthy && return 0
    sleep 3
  done
  echo "error: platform-pg is not healthy after 5 minutes; see kubectl get cluster,database -n databases" >&2
  return 1
}

# Installs the CloudNativePG operator, the Postgres cluster and Gitea with Helm.
phase_git_hosting() {
  step "CloudNativePG operator (helm, until Argo CD manages it)" "installed_or_adopted cloudnative-pg" "helm_install cloudnative-pg"
  step "platform-pg cluster and databases applied" "applied_or_adopted databases" "apply_manifests databases"
  step "platform-pg healthy, databases created" platform_pg_healthy wait_platform_pg
  step "Gitea (helm, until Argo CD manages it)" "installed_or_adopted gitea" "helm_install gitea"
}

# Gitea's public name only works once Argo CD has reconciled Traefik and the certificate, so
# phase 4 talks to Gitea through a temporary port-forward, killed when the script exits.
start_gitea_forward() {
  local log port=""
  log=$(mktemp)
  kubectl port-forward -n gitea svc/gitea-http 0:3000 >"$log" 2>&1 &
  GITEA_FORWARD_PID=$!
  trap 'kill "$GITEA_FORWARD_PID" 2>/dev/null' EXIT
  for _ in $(seq 50); do
    port=$(sed -n 's/^Forwarding from 127\.0\.0\.1:\([0-9]*\).*/\1/p' "$log")
    [[ -z $port ]] || break
    sleep 0.2
  done
  rm -f "$log"
  if [[ -z $port ]]; then
    $DRY_RUN && return 0 # nothing to talk to yet; every check below reports todo
    echo "error: cannot port-forward to Gitea" >&2
    return 1
  fi
  GITEA_URL=http://127.0.0.1:$port
}

# gitea_api <method> <path> [json]: the Gitea API as the admin. The password reaches curl
# through a netrc on a pipe, never as an argument.
gitea_api() {
  local data=()
  [[ -z ${3-} ]] || data=(-H 'Content-Type: application/json' --data "$3")
  curl -fsS --max-time 20 -X "$1" "${data[@]}" \
    --netrc-file <(printf 'machine 127.0.0.1 login gitea_admin password %s\n' "$(secret_value GITEA_ADMIN_PASSWORD)") \
    "${GITEA_URL:?}/api/v1$2"
}

# gitea_token_works <token>: the token can read the repository.
gitea_token_works() {
  [[ -n $1 ]] && curl -fsS --max-time 20 -o /dev/null \
    -H @<(printf 'Authorization: token %s\n' "$1") "${GITEA_URL:?}/api/v1/repos/$GITEA_REPO"
}

# new_gitea_token <name> <scope>: replaces the admin's token of that name and prints it. Gitea
# shows a token only once, so a lost one is recreated rather than looked up.
new_gitea_token() {
  gitea_api DELETE "/users/gitea_admin/tokens/$1" >/dev/null 2>&1 || true
  gitea_api POST /users/gitea_admin/tokens "{\"name\": \"$1\", \"scopes\": [\"$2\"]}" | jq -er .sha1
}

org_exists() { [[ -n ${GITEA_URL-} ]] && gitea_api GET /orgs/sdlc >/dev/null 2>&1; }
create_org() { gitea_api POST /orgs '{"username": "sdlc", "visibility": "private"}' >/dev/null; }

repo_exists() { [[ -n ${GITEA_URL-} ]] && gitea_api GET "/repos/$GITEA_REPO" >/dev/null 2>&1; }
create_repo() { gitea_api POST /orgs/sdlc/repos '{"name": "ai-native-sdlc", "private": true}' >/dev/null; }

push_token_works() {
  [[ -n ${GITEA_URL-} && -s $PUSH_TOKEN_FILE ]] && gitea_token_works "$(<"$PUSH_TOKEN_FILE")"
}

create_push_token() {
  local token
  token=$(new_gitea_token bootstrap-push write:repository)
  (umask 077 && printf '%s\n' "$token" >"$PUSH_TOKEN_FILE")
}

argocd_token() {
  kubectl get secret -n argocd repo-ai-native-sdlc -o jsonpath='{.data.password}' 2>/dev/null | base64 -d
}

argocd_token_works() { [[ -n ${GITEA_URL-} ]] && gitea_token_works "$(argocd_token)"; }

# The read-only token lives only in Argo CD's repository Secret, which Argo CD finds by label.
create_argocd_token() {
  local token
  token=$(new_gitea_token argocd-read read:repository)
  ensure_namespace argocd
  printf '%s' "$token" | jq -Rn --arg url "$ARGOCD_REPO_URL" '{
    apiVersion: "v1", kind: "Secret",
    metadata: {namespace: "argocd", name: "repo-ai-native-sdlc",
      labels: {"argocd.argoproj.io/secret-type": "repository", "app.kubernetes.io/managed-by": "ai-native-sdlc"}},
    stringData: {type: "git", url: $url, username: "gitea_admin", password: input}
  }' | kubectl apply --server-side --field-manager="$FIELD_MANAGER" -f - >/dev/null
}

origin_is_gitea() { [[ $(git remote get-url origin 2>/dev/null) == "$GITEA_REMOTE" ]]; }

# The previous origin is kept as "github", so nothing it references is lost.
move_origin() {
  local current github
  current=$(git remote get-url origin 2>/dev/null || true)
  if [[ -n $current ]]; then
    github=$(git remote get-url github 2>/dev/null || true)
    if [[ -z $github ]]; then
      git remote rename origin github
    elif [[ $github == "$current" ]]; then
      git remote remove origin
    else
      echo "error: origin ($current) cannot be kept as github, which points to $github" >&2
      return 1
    fi
  fi
  git remote add origin "$GITEA_REMOTE"
}

# The helper reads the push token from the secrets directory at the moment git asks, so the
# token is never written into .git/config or ~/.git-credentials. The empty first entry drops
# any helper inherited from global config for this URL.
credential_helper() {
  printf '%s' "!f() { test \"\$1\" = get || exit 0; echo username=gitea_admin; echo \"password=\$(cat '$PUSH_TOKEN_FILE')\"; }; f"
}

credential_helper_set() {
  [[ $(git config --get-all "credential.$GITEA_HOST.helper") == "$(printf '\n%s' "$(credential_helper)")" ]]
}

set_credential_helper() {
  git config --unset-all "credential.$GITEA_HOST.helper" || true
  git config --add "credential.$GITEA_HOST.helper" ""
  git config --add "credential.$GITEA_HOST.helper" "$(credential_helper)"
}

# git_via_forward <git args...>: git with Gitea's public URL rewritten to the port-forward and
# the same credential helper, so named-remote commands work before the ingress exists.
git_via_forward() {
  git -c "url.$GITEA_URL/.insteadOf=$GITEA_HOST/" -c credential.helper= \
    -c "credential.helper=$(credential_helper)" "$@"
}

local_refs() { git for-each-ref --format='%(objectname) %(refname)' refs/heads refs/tags | sort; }

gitea_has_local_refs() {
  [[ -n ${GITEA_URL-} ]] && origin_is_gitea || return 1
  local remote
  remote=$(git_via_forward ls-remote origin 'refs/heads/*' 'refs/tags/*' 2>/dev/null | grep -v '\^{}$' | awk '{ print $1, $2 }' | sort) &&
    [[ -z $(comm -23 <(local_refs) <(printf '%s\n' "$remote")) ]]
}

# main goes first: Gitea makes the first branch pushed to an empty repository its default
# branch, asynchronously, so pushing everything at once could leave another branch as default.
push_all_refs() {
  git show-ref --verify --quiet refs/heads/main && git_via_forward push origin refs/heads/main:refs/heads/main
  git_via_forward push origin 'refs/heads/*:refs/heads/*' 'refs/tags/*:refs/tags/*'
}

main_tracks_origin() {
  origin_is_gitea && [[ $(git config branch.main.remote) == origin && $(git config branch.main.merge) == refs/heads/main ]]
}

track_main() { git branch --set-upstream-to=origin/main main; }

default_branch_is_main() {
  [[ -n ${GITEA_URL-} ]] && [[ $(gitea_api GET "/repos/$GITEA_REPO" 2>/dev/null | jq -r .default_branch) == main ]]
}

set_default_branch() { gitea_api PATCH "/repos/$GITEA_REPO" '{"default_branch": "main"}' >/dev/null; }

# Creates the Gitea org and repo, moves origin to Gitea and pushes branches and tags.
phase_repository() {
  start_gitea_forward
  step "Gitea org sdlc exists" org_exists create_org
  step "private repo $GITEA_REPO exists" repo_exists create_repo
  step "push token in the secrets directory works" push_token_works create_push_token
  step "Argo CD's read token works" argocd_token_works create_argocd_token
  step "origin is $GITEA_REMOTE (the old one kept as github)" origin_is_gitea move_origin
  step "credential helper for $GITEA_HOST reads the push token" credential_helper_set set_credential_helper
  step "Gitea has every local branch and tag" gitea_has_local_refs push_all_refs
  step "main tracks origin/main" main_tracks_origin track_main
  step "the Gitea repo's default branch is main" default_branch_is_main set_default_branch
}

# app_adopted <component>: Argo CD has an Application for it. From then on Argo CD alone
# changes it, and the bootstrap leaves it alone.
app_adopted() { kubectl get application -n argocd "$1" >/dev/null 2>&1; }

installed_or_adopted() { app_adopted "$1" || helm_release_current "$1"; }

applied_or_adopted() { app_adopted "$1" || manifests_current "$1"; }

root_app_current() {
  kubectl diff --server-side --field-manager="$FIELD_MANAGER" -f platform/argocd/root.yaml >/dev/null 2>&1
}

apply_root_app() { kubectl apply --server-side --field-manager="$FIELD_MANAGER" -f platform/argocd/root.yaml; }

# Installs Argo CD with Helm and applies the root Application.
phase_gitops() {
  step "Argo CD (helm, until it manages itself)" "installed_or_adopted argocd" "helm_install argocd"
  step "root Application applied" root_app_current apply_root_app
}

all_apps_healthy() {
  kubectl get applications -n argocd -o json 2>/dev/null | jq -e '
    (.items | length) > 1 and
    all(.items[]; .status.sync.status == "Synced" and .status.health.status == "Healthy")' >/dev/null
}

wait_all_apps() {
  local i
  for i in $(seq 120); do
    all_apps_healthy && return 0
    sleep 5
  done
  echo "error: not every Application is Synced and Healthy after 10 minutes:" >&2
  kubectl get applications -n argocd >&2
  return 1
}

# Releases the bootstrap installed with Helm before Argo CD took them over.
HELM_RELEASES=(cloudnative-pg/cloudnative-pg gitea/gitea argocd/argocd)

helm_records_gone() {
  local entry
  for entry in "${HELM_RELEASES[@]}"; do
    [[ -z $(kubectl get secret -n "${entry%/*}" -l "owner=helm,name=${entry#*/}" -o name 2>/dev/null) ]] || return 1
  done
}

# Deleting the release records makes Helm forget the releases while every resource stays.
# helm uninstall would delete the resources themselves.
drop_helm_records() {
  local entry
  for entry in "${HELM_RELEASES[@]}"; do
    kubectl delete secret -n "${entry%/*}" -l "owner=helm,name=${entry#*/}"
  done
}

# Waits until Argo CD has everything Synced/Healthy, then drops the Helm release records.
phase_adoption() {
  step "every Application is Synced and Healthy" all_apps_healthy wait_all_apps
  step "no Helm release records left: Argo CD owns the components" helm_records_gone drop_helm_records
}

